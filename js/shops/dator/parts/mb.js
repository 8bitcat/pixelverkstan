const GREENS = ['#2e6b3c', '#2b6538', '#336f3f', '#2a5f35'];
function look(brand, name, y) {
  const N = name.toUpperCase(), h = hash(name);
  if (y < 1997) return { pcb: GREENS[h % 4], accent: ['#d9cfae', '#1d1d1d', '#e8e2cc'][h % 3] };
  if (/LANPARTY/.test(N)) return { pcb: '#1c1c1c', accent: '#e07a2e' };
  if (/TUF|SABERTOOTH/.test(N)) return { pcb: '#2a2b26', accent: '#d8b24a' };
  if (/PROART/.test(N)) return { pcb: '#1c1c1e', accent: '#c9a86a' };
  if (/ ROG |MAXIMUS|RAMPAGE|CROSSHAIR|ZENITH|STRIKER/.test(N)) return { pcb: '#1b1d22', accent: '#c9323a' };
  if (/AORUS|G1\.|GAMING [579]|GAMING K[57]|SOC/.test(N) && brand === 'Gigabyte') return { pcb: '#1f2124', accent: '#e07a2e' };
  if (/FATAL1TY|PHANTOM|PG |RIPTIDE|LIGHTNING/.test(N)) return { pcb: '#1b1b1d', accent: '#c9323a' };
  if (/TAICHI/.test(N)) return { pcb: '#1f1f1f', accent: '#c9a86a' };
  if (/STEEL LEGEND/.test(N)) return { pcb: '#3a3d42', accent: '#e9e9e6' };
  if (/ MEG |GODLIKE/.test(N)) return { pcb: '#1a1b1e', accent: '#d8b24a' };
  if (/ MPG .*EDGE/.test(N)) return { pcb: '#2b2f36', accent: '#e9e9e6' };
  if (/ MPG |CARBON/.test(N)) return { pcb: '#1f2124', accent: '#c9323a' };
  if (/ MAG |TOMAHAWK|MORTAR/.test(N)) return { pcb: '#23262b', accent: '#8a9199' };
  if (/ PRIME /.test(N)) return { pcb: '#23262b', accent: '#e9e9e6' };
  if (/ STRIX/.test(N)) return { pcb: '#1b1d22', accent: '#c9323a' };
  if (/BLACKOPS|BLOODRAGE/.test(N)) return { pcb: '#1b1b1b', accent: '#3ac0e0' };
  const era = ERA[brand];
  if (era) { const e = era.find((r) => y <= r[0]) || era[era.length - 1]; return { pcb: e[1], accent: e[2] }; }
  return { pcb: GREENS[h % 4], accent: ['#e0c040', '#1d1d1d', '#c8ccd0'][h % 3] };
}

function G(d, rows) {
  const end = SOCKETS[d.s].years[1];
  for (const r of rows) {
    const [name, year, usd, tier, fl = '', x = {}] = r;
    const F = fl.split(' ').filter(Boolean), has = (t) => F.includes(t);
    const fk = F.find((t) => FORM[t]);
    const form = fk ? FORM[fk] : d.f;
    const small = form === 'ITX' ? 'I' : form === 'mATX' ? 'M' : '';
    const rs = x.rs ?? (small === 'I' ? Math.min(2, d.rs) : small === 'M' ? (d.rsM ?? d.rs) : d.rs);
    const max = x.max ?? Math.max(1, Math.round((d.max * rs) / d.rs));
    const st = new Set(d.st || []);
    for (const [flag, k] of [['ide', 'IDE'], ['sata', 'SATA'], ['n', 'NVMe']]) { if (has(flag)) st.add(k); if (has('-' + flag)) st.delete(k); }
    const u = F.find((t) => /^u\d{4}$/.test(t));
    const until = Math.max(year, Math.min(2026, u ? +u.slice(1) : Math.min(end, year + (d.life ?? 3))));
    let power = has('p20') ? 'ATX20' : has('p24') ? 'ATX24' : d.pw;
    if (AT_FORMS.includes(form)) power = 'AT'; else if (power === 'AT') power = 'ATX20';
    const cpuPower = has('cp0') ? null : has('cp4') ? 'ATX12V4' : has('cp8') ? 'EPS8' : AT_FORMS.includes(form) ? null : d.cp ?? null;
    const bool = (k, def) => (has(k) ? true : has('-' + k) ? false : !!def);
    const brand = x.brand ?? name.split(' ')[0];
    let id = x.id ?? 'mb-' + slug(name);
    if (IDS.has(id)) id += '-' + year;
    IDS.add(id);
    const lk = look(brand, name, year);
    P.push({
      id, cat: 'mb', name, brand, year, until, cost: x.cost ?? sek(usd, year), tier, rgb: has('r'),
      socket: d.s, chipset: x.c ?? d.c, form, ram: x.ram ?? d.ram, ramSlots: rs, ramMaxMB: max,
      slots: SL(x.sl ?? (small === 'I' ? d.slI : small === 'M' ? d.slM : null) ?? d.sl),
      storage: ['IDE', 'SATA', 'NVMe'].filter((k) => st.has(k)),
      floppy: bool('fd', d.fd), power, cpuPower, video: bool('v', d.vid), audio: bool('a', d.aud),
      look: { pcb: x.pcb ?? lk.pcb, accent: x.acc ?? lk.accent },
    });
  }
}

