// Gigabyte, DFI, EPoX, Soyo, Tyan, Intel, Supermicro, ASRock, EVGA, Biostar, Foxconn m.fl.
// Genereras ur tabeller per plattform (sockel + kretsuppsättning).
//
// Plattform d: { s: sockel, c: chipset, ram, rs: RAM-platser, max: max-RAM i MB,
//   sl / slM / slI: kortplatser 'isa8/isa16/vlb/pci/agp/pcie' för fullformat / mATX / ITX,
//   st: inbyggd lagring, fd: diskettkontroller, pw: ström, cp: CPU-ström, vid, aud, f: format, life }
// Rad: [namn, år, lanseringspris USD, segment, flaggor?, extra?]
//   flaggor (mellanslag): X T B A M I = format XT/AT/BabyAT/ATX/mATX/ITX, v/-v inbyggd grafik,
//   a/-a ljud, r RGB, fd/-fd diskettkontroller, ide/-ide, sata/-sata, n/-n (NVMe),
//   p20/p24 ATX-ström, cp0/cp4/cp8 CPU-ström, u<år> sista säljår
//   extra: { c: chipset, sl, rs, max, ram, id, cost, pcb, acc, brand }
// Pris = USD × SEK_PER_USD[år] × 1,25. RAM-tak under 1 MB (XT/tidiga AT) avrundas upp till 1 MB.
// video = grafik i kretsuppsättningen (i810, 865G, 780G …) – processorgrafik (APU/iGPU) räknas på CPU:n.
// pcie = antal PCIe-platser (x1 + x16). EISA-platser räknas som isa16. i850-kort (RDRAM) har ram 'SDR'
// eftersom kanon saknar RDRAM.
import { SEK_PER_USD, SOCKETS } from './canon.js';

const P = [];
const IDS = new Set();
const slug = (s) => s.toLowerCase().replace(/\+/g, 'plus').replace(/&/g, 'and').replace(/[^a-z0-9.]+/g, '-').replace(/^-+|-+$/g, '');
const rnd = (v) => (v < 1000 ? Math.max(10, Math.round(v / 5) * 5) : Math.round(v / 10) * 10);
const sek = (usd, y) => rnd(usd * SEK_PER_USD[y] * 1.25);
const SL = (s) => { const [isa8, isa16, vlb, pci, agp, pcie] = s.split('/').map(Number); return { isa8, isa16, vlb, pci, agp, pcie }; };
const FORM = { X: 'XT', T: 'AT', B: 'BabyAT', A: 'ATX', M: 'mATX', I: 'ITX' };
const AT_FORMS = ['XT', 'AT', 'BabyAT'];
const hash = (s) => { let h = 7; for (const ch of s) h = (h * 31 + ch.charCodeAt(0)) >>> 0; return h; };

// Kortfärger per tillverkare och epok: [till och med år, pcb, accent]
