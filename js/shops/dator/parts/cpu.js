// Processorer 1983–2026 – riktiga desktop-CPU:er från Intel, AMD, NEC, Harris,
// Siemens, Cyrix, IBM, TI, UMC, IDT, VIA och Rise. Genereras ur tabeller per sockel.
// Rad: [namn, år, sista säljår, MHz, kärnor, TDP W, lanseringspris USD, segment, extra?]
// Pris = USD × SEK_PER_USD[år] × 1,25 (avrundat). TDP för 1980-talskretsar är uppskattad.
import { SEK_PER_USD } from './canon.js';

const P = [];
const slug = (s) => s.toLowerCase().replace(/µ/g, 'u').replace(/\+/g, 'plus').replace(/[^a-z0-9.]+/g, '-').replace(/^-+|-+$/g, '');
const rnd = (v) => (v < 1000 ? Math.max(10, Math.round(v / 5) * 5) : Math.round(v / 10) * 10);
const sek = (usd, y) => rnd(usd * SEK_PER_USD[y] * 1.25);

// d = gruppens standardvärden: { socket, brand, lb (look.brand), pkg, needs, igpu: true|false|'noF', pre, fits }
function G(d, rows) {
  for (const r of rows) {
    const [n, year, until, mhz, cores, watt, usd, tier, x = {}] = r;
    const name = (x.pre ?? d.pre ?? '') + n;
    const igpu = x.igpu ?? (d.igpu === 'noF' ? !/F$/.test(n) : !!d.igpu);
    const fits = x.fits ?? d.fits;
    const p = {
      id: x.id ?? 'cpu-' + slug(name),
      cat: 'cpu', name, brand: x.brand ?? d.brand, year, until: Math.max(year, Math.min(2026, until)),
      cost: x.cost ?? sek(usd, year), tier, rgb: false,
      socket: x.socket ?? d.socket, mhz, cores, watt, igpu, needs: x.needs ?? d.needs,
      look: { brand: x.lb ?? d.lb, pkg: x.pkg ?? d.pkg, ...(x.look || {}) },
    };
    if (fits && fits.length) p.fits = fits;
    P.push(p);
  }
}

