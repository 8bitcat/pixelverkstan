const TYPE = { mfm: ['MFM', 'hdd'], ide: ['IDE', 'hdd'], sata: ['SATA', 'hdd'], ssd: ['SATA', 'ssd'], nvme: ['NVMe', 'nvme'] };
const FORM = { 'mfm-fh': '5.25', 'hdd-hh': '5.25', hdd35: '3.5', ssd25: '2.5', m2: 'M.2', 'm2-heatsink': 'M.2' };

const P = [];
function add(t, brand, name, year, until, mb, usd, tier, label, o = {}) {
  const [iface, kind] = TYPE[t];
  const style = o.style || (t === 'nvme' ? (o.hs ? 'm2-heatsink' : 'm2') : t === 'ssd' ? 'ssd25' : 'hdd35');
  const L = LEGACY[name];
  P.push({
    id: L ? L.id : 'sto-' + slug(name), cat: 'storage', name, brand,
    year, until: Math.max(year, Math.min(2026, until)), cost: kr(usd, year), tier: Math.max(1, Math.min(5, tier)),
    iface, kind, mb, form: FORM[style], look: L ? { ...L.look, style } : { label, style },
  });
}
// Serie: rader = [suffix, MB, usd, tier?, { y, u, hs, style }?]
function S(t, brand, base, year, until, tier, label, rows, o = {}) {
  for (const [suffix, mb, usd, rt, x = {}] of rows) {
    add(t, brand, base ? `${base} ${suffix}` : suffix, x.y ?? year, x.u ?? until, mb, usd, rt ?? tier, x.label ?? label, { ...o, ...x });
  }
}
